import { useEffect, useState } from 'react';
import {
  Calculator,
  ClipboardList,
  Hammer,
  Menu,
  PackagePlus,
  Sparkles,
  User,
  X,
} from 'lucide-react';
import { ClientWorkspace } from './components/ClientWorkspace.tsx';
import { WorkshopWorkspace } from './components/WorkshopWorkspace.tsx';
import { DEFAULT_CATALOG_ITEMS } from './data/presets.ts';
import {
  DEFAULT_ROOM_CATEGORIES,
  type AppMode,
  type CatalogItem,
  type FurnitureOrder,
  type MaterialPricing,
} from './types.ts';
import { DEFAULT_MATERIAL_PRICING } from './utils/furnitureCalculator.ts';
import {
  applyTelegramThemeAndViewport,
  getTelegramUser,
  tgHapticImpact,
  tgHapticSelection,
  type TelegramUserInfo,
} from './utils/telegram.ts';

const RSM_LOGO_SRC = '/src/assets/images/rsm_cut_logo_1795695300264.jpg';

type WorkshopTab = 'orders' | 'catalog' | 'pricing';

export default function App() {
  const [mode, setMode] = useState<AppMode>('client');
  const [workshopTab, setWorkshopTab] = useState<WorkshopTab>('orders');
  const [pricing, setPricing] = useState<MaterialPricing>(DEFAULT_MATERIAL_PRICING);
  const [catalog, setCatalog] = useState<CatalogItem[]>(DEFAULT_CATALOG_ITEMS);
  const [categories, setCategories] = useState<string[]>([...DEFAULT_ROOM_CATEGORIES]);
  const [orders, setOrders] = useState<FurnitureOrder[]>([]);
  const [loading, setLoading] = useState(true);
  const [logoError, setLogoError] = useState(false);
  const [isDrawerOpen, setIsDrawerOpen] = useState(false);
  const [tgUser, setTgUser] = useState<TelegramUserInfo>(() => getTelegramUser());

  useEffect(() => {
    const cleanupTg = applyTelegramThemeAndViewport();
    setTgUser(getTelegramUser());

    let active = true;
    fetch('/api/workshop/state')
      .then((res) => res.json())
      .then((data) => {
        if (!active) return;
        if (data.pricing) setPricing(data.pricing);
        if (Array.isArray(data.catalog) && data.catalog.length > 0) {
          setCatalog(data.catalog);
        }
        if (Array.isArray(data.categories) && data.categories.length > 0) {
          setCategories(data.categories);
        }
        if (Array.isArray(data.orders)) setOrders(data.orders);
      })
      .catch((err) => {
        console.error('Failed to load RSM CUT state:', err);
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
      cleanupTg();
    };
  }, []);

  useEffect(() => {
    if (!isDrawerOpen) return;
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        setIsDrawerOpen(false);
      }
    };
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [isDrawerOpen]);

  const handleOrderCreated = (newOrder: FurnitureOrder) => {
    setOrders((prev) => [newOrder, ...prev]);
  };

  const handleOrderUpdated = (updated: FurnitureOrder) => {
    setOrders((prev) => prev.map((o) => (o.id === updated.id ? updated : o)));
  };

  const handleCatalogAdded = (item: CatalogItem) => {
    setCatalog((prev) => [item, ...prev]);
    setCategories((prev) => (prev.includes(item.category) ? prev : [...prev, item.category]));
  };

  const handleCatalogDeleted = (id: string) => {
    setCatalog((prev) => prev.filter((c) => c.id !== id));
  };

  const handleCategoryAutoGenerated = (
    categoryName: string,
    items: CatalogItem[],
    nextCategories?: string[],
  ) => {
    setCatalog((prev) => {
      const existingIds = new Set(prev.map((c) => c.id));
      const fresh = items.filter((item) => !existingIds.has(item.id));
      return [...fresh, ...prev];
    });
    setCategories((prev) =>
      nextCategories && nextCategories.length > 0
        ? nextCategories
        : prev.includes(categoryName)
          ? prev
          : [...prev, categoryName],
    );
  };

  const handleModeSwitch = (nextMode: AppMode, targetWorkshopTab?: WorkshopTab) => {
    tgHapticSelection();
    setMode(nextMode);
    if (nextMode === 'workshop' && targetWorkshopTab) {
      setWorkshopTab(targetWorkshopTab);
    }
    setIsDrawerOpen(false);
  };

  const newOrdersCount = orders.filter((o) => o.status === 'Yangi').length;

  return (
    <div
      className="min-h-[100dvh] w-full max-w-[430px] mx-auto flex flex-col justify-between bg-[#FAF8F5] text-[#1A2421] relative sm:shadow-[0_0_40px_rgba(14,58,47,0.08)] sm:border-x sm:border-[#C5A059]/25 overflow-x-clip"
      style={{ minHeight: 'var(--tg-viewport-stable-height, 100dvh)' }}
    >
      {/* Fixed Top Header on All 4 Tabs */}
      <header className="sticky top-0 z-40 h-[62px] shrink-0 bg-[#FAF8F5]/95 backdrop-blur-md border-b border-[#C5A059]/30 px-4 flex items-center justify-between gap-3">
        <div className="flex items-center gap-2.5 min-w-0">
          <div className="w-10 h-10 p-0.5 rounded-xl bg-[#0E3A2F] border border-[#C5A059] shadow-xs shrink-0 flex items-center justify-center overflow-hidden">
            {!logoError ? (
              <img
                src={RSM_LOGO_SRC}
                alt="RSM CUT logotipi"
                referrerPolicy="no-referrer"
                onError={() => setLogoError(true)}
                className="w-full h-full rounded-[9px] object-cover"
              />
            ) : (
              <span className="text-[11px] font-bold tracking-wider text-[#C5A059]">RSM</span>
            )}
          </div>
          <div className="min-w-0">
            <div className="flex items-baseline gap-1.5 min-w-0">
              <span className="text-[15px] font-bold tracking-wide text-[#0E3A2F] whitespace-nowrap leading-tight">
                RSM <span className="text-[#C5A059]">CUT</span>
              </span>
              {mode === 'workshop' && (
                <span className="text-[10px] font-bold px-1.5 py-0.5 rounded bg-[#0E3A2F] text-[#C5A059] border border-[#C5A059]/60">
                  USTA
                </span>
              )}
            </div>
            <p className="text-[11px] text-[#6B7A74] font-medium truncate leading-tight">
              AI Konstruktor
            </p>
          </div>
        </div>

        <button
          type="button"
          onClick={() => {
            tgHapticSelection();
            setIsDrawerOpen((v) => !v);
          }}
          aria-label="Menyu"
          aria-expanded={isDrawerOpen}
          className="w-10 h-10 rounded-full bg-[#0E3A2F] hover:bg-[#144D3E] border border-[#C5A059] text-[#C5A059] flex items-center justify-center shadow-sm transition-transform active:scale-95 shrink-0 relative"
        >
          {isDrawerOpen ? <X className="w-5 h-5" /> : <Menu className="w-5 h-5" />}
          {!isDrawerOpen && newOrdersCount > 0 && (
            <span className="absolute -top-0.5 -right-0.5 w-3 h-3 rounded-full bg-[#C5A059] border-2 border-[#FAF8F5]" />
          )}
        </button>
      </header>

      {/* Main Content Area */}
      <main className="flex-1 flex flex-col min-h-0">
        {loading ? (
          <div className="px-4 py-6 space-y-4">
            <div className="h-9 rounded-full bg-white border border-[#C5A059]/30 animate-pulse" />
            <div className="h-80 rounded-3xl bg-white border border-[#C5A059]/30 animate-pulse" />
          </div>
        ) : mode === 'client' ? (
          <ClientWorkspace
            pricing={pricing}
            catalog={catalog}
            categories={categories}
            telegramUser={tgUser}
            onOrderCreated={handleOrderCreated}
            onSwitchToWorkshop={() => handleModeSwitch('workshop', 'orders')}
          />
        ) : (
          <WorkshopWorkspace
            pricing={pricing}
            catalog={catalog}
            categories={categories}
            orders={orders}
            requestedTab={workshopTab}
            onTabChange={setWorkshopTab}
            onPricingSaved={setPricing}
            onCatalogAdded={handleCatalogAdded}
            onCatalogDeleted={handleCatalogDeleted}
            onCategoryGenerated={handleCategoryAutoGenerated}
            onOrderUpdated={handleOrderUpdated}
          />
        )}
      </main>

      {/* Slide-out Right-Side Luxury Drawer */}
      {isDrawerOpen && (
        <div
          className="fixed inset-0 z-50 flex justify-end bg-[#0E3A2F]/35 backdrop-blur-xs"
          onClick={() => setIsDrawerOpen(false)}
        >
          <aside
            role="dialog"
            aria-label="RSM CUT Menyu"
            onClick={(e) => e.stopPropagation()}
            className="w-[82%] max-w-[320px] h-full bg-[#FAF8F5] text-[#1A2421] border-l border-[#C5A059]/50 shadow-2xl flex flex-col justify-between p-4"
            style={{ paddingBottom: 'max(1rem, var(--tg-safe-bottom, 0px))' }}
          >
            <div className="space-y-4">
              <div className="flex items-center justify-between pb-3 border-b border-[#C5A059]/30">
                <div className="flex items-center gap-2.5">
                  <div className="w-9 h-9 rounded-xl bg-[#0E3A2F] border border-[#C5A059] flex items-center justify-center text-xs font-bold text-[#C5A059]">
                    RSM
                  </div>
                  <div>
                    <p className="text-sm font-bold text-[#0E3A2F]">
                      RSM <span className="text-[#C5A059]">CUT</span>
                    </p>
                    <p className="text-[11px] text-[#6B7A74]">Ravshan Samarqand Mebel</p>
                  </div>
                </div>
                <button
                  type="button"
                  onClick={() => setIsDrawerOpen(false)}
                  aria-label="Menyuni yopish"
                  className="w-9 h-9 rounded-full bg-white border border-[#C5A059]/45 text-[#0E3A2F] flex items-center justify-center"
                >
                  <X className="w-4 h-4" />
                </button>
              </div>

              {tgUser.firstName && (
                <div className="px-3 py-2.5 rounded-2xl bg-white border border-[#C5A059]/40 flex items-center gap-2.5">
                  <div className="w-8 h-8 rounded-full bg-[#0E3A2F] text-[#C5A059] flex items-center justify-center shrink-0">
                    <User className="w-4 h-4" />
                  </div>
                  <div className="min-w-0">
                    <p className="text-xs font-bold text-[#1A2421] truncate">
                      Salom, {tgUser.fullName || tgUser.firstName}!
                    </p>
                    {tgUser.username && (
                      <p className="text-[11px] text-[#6B7A74] truncate">@{tgUser.username}</p>
                    )}
                  </div>
                </div>
              )}

              {/* Mode Switcher */}
              <div className="space-y-1.5">
                <p className="text-[11px] font-bold tracking-wider uppercase text-[#6B7A74] px-1">
                  Ish rejimi
                </p>
                <div className="grid grid-cols-2 gap-1.5 p-1 bg-white rounded-2xl border border-[#C5A059]/40">
                  <button
                    type="button"
                    onClick={() => handleModeSwitch('client')}
                    className={`min-h-[40px] px-2.5 rounded-xl text-xs font-semibold transition-all ${
                      mode === 'client'
                        ? 'bg-[#0E3A2F] text-white border border-[#C5A059]'
                        : 'text-[#1A2421] hover:bg-[#FAF8F5]'
                    }`}
                  >
                    Mijoz rejimi
                  </button>
                  <button
                    type="button"
                    onClick={() => handleModeSwitch('workshop', 'orders')}
                    className={`min-h-[40px] px-2.5 rounded-xl text-xs font-semibold flex items-center justify-center gap-1.5 transition-all ${
                      mode === 'workshop'
                        ? 'bg-[#0E3A2F] text-white border border-[#C5A059]'
                        : 'text-[#1A2421] hover:bg-[#FAF8F5]'
                    }`}
                  >
                    <Hammer className="w-3.5 h-3.5 text-[#C5A059]" />
                    <span>Usta rejimi</span>
                  </button>
                </div>
              </div>

              {/* Workshop & Catalog Quick Links */}
              <div className="space-y-2">
                <p className="text-[11px] font-bold tracking-wider uppercase text-[#6B7A74] px-1">
                  Boshqaruv va sozlamalar
                </p>

                <button
                  type="button"
                  onClick={() => {
                    tgHapticImpact('light');
                    handleModeSwitch('workshop', 'pricing');
                  }}
                  className="w-full min-h-[46px] px-3.5 rounded-2xl bg-white hover:bg-[#F5F1E8] border border-[#C5A059]/45 flex items-center justify-between text-left transition-colors"
                >
                  <span className="flex items-center gap-2.5 text-xs font-semibold text-[#1A2421]">
                    <Calculator className="w-4 h-4 text-[#0E3A2F]" />
                    <span>Material narxlari</span>
                  </span>
                  <span className="text-[10px] font-bold text-[#C5A059]">Sozlash</span>
                </button>

                <button
                  type="button"
                  onClick={() => {
                    tgHapticImpact('light');
                    handleModeSwitch('workshop', 'catalog');
                  }}
                  className="w-full min-h-[46px] px-3.5 rounded-2xl bg-white hover:bg-[#F5F1E8] border border-[#C5A059]/45 flex items-center justify-between text-left transition-colors"
                >
                  <span className="flex items-center gap-2.5 text-xs font-semibold text-[#1A2421]">
                    <PackagePlus className="w-4 h-4 text-[#0E3A2F]" />
                    <span>Yangi katalog qo&apos;shish</span>
                  </span>
                  <Sparkles className="w-3.5 h-3.5 text-[#C5A059]" />
                </button>

                <button
                  type="button"
                  onClick={() => {
                    tgHapticImpact('light');
                    handleModeSwitch('workshop', 'orders');
                  }}
                  className="w-full min-h-[46px] px-3.5 rounded-2xl bg-white hover:bg-[#F5F1E8] border border-[#C5A059]/45 flex items-center justify-between text-left transition-colors"
                >
                  <span className="flex items-center gap-2.5 text-xs font-semibold text-[#1A2421]">
                    <ClipboardList className="w-4 h-4 text-[#0E3A2F]" />
                    <span>Sex buyurtmalari (2D Raskroy)</span>
                  </span>
                  {orders.length > 0 && (
                    <span className="px-2 py-0.5 rounded-full bg-[#0E3A2F] text-[#C5A059] text-[10px] font-bold font-mono-num">
                      {orders.length}
                    </span>
                  )}
                </button>
              </div>
            </div>

            <div className="pt-3 border-t border-[#C5A059]/30 text-center">
              <p className="text-[11px] font-semibold text-[#0E3A2F]">
                RSM CUT · AI Konstruktor &amp; Raskroy
              </p>
              <p className="text-[10px] text-[#6B7A74] mt-0.5">
                Ravshan Samarqand Mebel
              </p>
            </div>
          </aside>
        </div>
      )}
    </div>
  );
}
